// the one list that grows with every feature, and `generate_handler!` needs the full path of each
// command in a single invocation - it cannot be assembled from several modules.
//
// All of these resolve on every platform: Windows-only features register a stub (or a command that
// returns a clear "not supported here" error) rather than being cfg'd out of this list, so the
// frontend can always call them and branch on the result.

